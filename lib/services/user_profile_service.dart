import 'tulpar_api_client.dart';

class UserProfile {
  const UserProfile({
    required this.name,
    required this.phone,
    required this.averageRating,
    this.carModel = '',
  });

  final String name;
  final String phone;
  final double averageRating;
  final String carModel;
}

abstract interface class UserProfileRepository {
  Future<UserProfile?> load(String userId);

  Future<void> update({
    required String userId,
    required String name,
    required String carModel,
  });
}

/// ???????? ?????? ????????? ??? ????????????? ? ???????????? UI ? ???????.
/// ?????????? ?????? ?????? ???????? ? ??????????? ????? VPS/PostgreSQL.
class FirebaseUserProfileRepository implements UserProfileRepository {
  FirebaseUserProfileRepository({TulparApiClient? apiClient})
    : _apiClient = apiClient ?? TulparApiClient();

  final TulparApiClient _apiClient;

  @override
  Future<UserProfile?> load(String userId) async {
    // ??????????? ??????? ?????? ???????????? ? PostgreSQL.
    await _apiClient.syncCurrentUser();

    final user = await _apiClient.getCurrentUserProfile();

    if (user.isEmpty) {
      return null;
    }

    Map<String, dynamic>? driver;

    try {
      driver = await _apiClient.getCurrentDriverProfile();
    } catch (_) {
      // ??????? ????????? ?? ?????? ????? driver_profiles.
      driver = null;
    }

    final ratingSum = (user['ratingSum'] as num?)?.toDouble() ?? 0;

    final ratingCount = (user['ratingCount'] as num?)?.toInt() ?? 0;

    final fallbackRating = (user['rating'] as num?)?.toDouble() ?? 5;

    final averageRating = ratingCount > 0
        ? ratingSum / ratingCount
        : fallbackRating;

    return UserProfile(
      name: user['name']?.toString() ?? '',
      phone: user['phone']?.toString() ?? '',
      averageRating: averageRating,
      carModel: driver?['carModel']?.toString() ?? '',
    );
  }

  @override
  Future<void> update({
    required String userId,
    required String name,
    required String carModel,
  }) async {
    final normalizedName = name.trim();

    await _apiClient.updateCurrentUserProfile(name: normalizedName);

    final normalizedCarModel = carModel.trim();

    // ? ????????? ???? ?????? ? driver_profiles ?????? ?? ???????.
    if (normalizedCarModel.isEmpty) {
      return;
    }

    final driver = await _apiClient.getCurrentDriverProfile();

    // ???? ??? ?? ????????, ????????? ?????? ???????????? ?????? ?
    // ?????????? ???????? ?????? ????? API exception.
    if (driver == null) {
      throw const TulparApiException(404, 'Профиль водителя не найден.');
    }

    await _apiClient.updateCurrentDriverVehicleModel(
      carModel: normalizedCarModel,
    );
  }
}

/// ????????? ??? ????????????? ?? ??????? unit-???????.
Map<String, Object> buildUserProfileUpdateData({
  required String name,
  required String carModel,
}) {
  final data = <String, Object>{'name': name.trim()};

  final normalizedCarModel = carModel.trim();

  if (normalizedCarModel.isNotEmpty) {
    data['carModel'] = normalizedCarModel;
  }

  return data;
}
